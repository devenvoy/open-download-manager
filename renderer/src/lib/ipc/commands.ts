/**
 * Command names, copied from `generate_handler!` in src-tauri/src/lib.rs.
 * This map is generated by `ts-rs` in step 5; until then, a new command must
 * be added to both sides in the same commit.
 *
 * Every command the app registers has an entry here, so a typo in the name is
 * a compile error rather than a runtime "command not found".
 */
export interface CommandMap {
  // Startup instrumentation
  mark_ui_ready: { args: { label?: string } | undefined; result: void };
  window_ready: { args: { label?: string } | undefined; result: void };
  take_add_window_options: {
    args: undefined;
    result: { paste?: boolean; scheduled?: string } | null;
  };

  // Snapshot and downloads
  snapshot: { args: undefined; result: Snapshot };
  add_download: { args: { request: DownloadRequest }; result: string[] };
  download_action: {
    args: { id: string; action: DownloadActionKind };
    result: void;
  };
  remove_completed: { args: undefined; result: string[] };
  review_download: {
    args: { request: ReviewDownloadRequest };
    result: string[];
  };
  check_destination_conflict: {
    args: { directory: string; filename: string };
    result: ConflictResolutionOutcome;
  };
  update_download_completion_actions: {
    args: { id: string; actions: CompletionAction[] | null };
    result: void;
  };
  retry_download_actions: { args: { id: string }; result: void };
  export_downloads_to_file: { args: undefined; result: void };
  import_downloads_from_file: { args: undefined; result: void };

  // Settings
  update_settings: { args: { patch: SettingsPatch }; result: Settings };
  validate_directory: { args: { path: string }; result: void };
  show_about_dialog: { args: undefined; result: void };
  check_for_updates: { args: undefined; result: void };

  // Windows
  open_progress_window: { args: { id: string }; result: void };
  close_auxiliary_window: { args: undefined; result: void };
  resize_auxiliary_window: {
    args: { width?: number | null; height?: number | null };
    result: void;
  };
  resize_progress_window: { args: { expanded: boolean }; result: void };
  open_options_window: { args: undefined; result: void };
  open_add_window: {
    args: { options?: { paste?: boolean; scheduled?: string } | null };
    result: void;
  };
  open_scheduler_window: { args: undefined; result: void };
  open_integration_window: { args: undefined; result: void };
  open_torrent_window: { args: undefined; result: void };
  tray_set_active_downloads: { args: { count: number }; result: void };

  // Browser integration
  get_integration_info: { args: undefined; result: Snapshot["integration"] };
  register_browser: {
    args: { browser: string; extensionId: string };
    result: void;
  };
  browser_setup_action: {
    args: { action: string; browser: string };
    result: BrowserSetupResult;
  };
  get_advanced_integration_capability: {
    args: undefined;
    result: AdvancedIntegrationCapability;
  };
  enable_advanced_integration: {
    args: { consent: boolean };
    result: AdvancedIntegrationCapability;
  };
  disable_advanced_integration: {
    args: undefined;
    result: AdvancedIntegrationCapability;
  };
  repair_advanced_integration: {
    args: undefined;
    result: AdvancedIntegrationCapability;
  };

  // Clipboard
  dismiss_clipboard_candidate: { args: { url: string }; result: void };

  // Media
  get_playlist_info: { args: { url: string }; result: PlaylistMetadata };
  resolve_asx_playlist: {
    args: { urlOrContent: string };
    result: AsxPlaylist;
  };
  get_video_formats: { args: { url: string }; result: YouTubeFormatChoice[] };
  add_playlist_downloads: {
    args: {
      request: {
        playlistId: string;
        playlistTitle: string;
        items: Array<{ id: string; url: string }>;
        commonCategory?: string | null;
        commonDirectory?: string | null;
      };
    };
    result: number;
  };
  get_media_tools_status: { args: undefined; result: MediaToolStatus[] };
  install_media_tool: { args: { tool: MediaToolType }; result: MediaToolStatus };

  // Queues and schedules
  list_queues: { args: undefined; result: DownloadQueue[] };
  create_queue: {
    args: {
      name: string;
      concurrencyLimit?: number | null;
      speedLimitKbps?: number | null;
      schedule?: QueueSchedule | null;
    };
    result: DownloadQueue;
  };
  update_queue: {
    args: {
      id: string;
      name?: string | null;
      enabled?: boolean | null;
      concurrencyLimit?: number | null;
      speedLimitKbps?: number | null;
      schedule?: QueueSchedule | null;
    };
    result: DownloadQueue;
  };
  delete_queue: {
    args: { id: string; disposition?: QueueDisposition | null };
    result: string[];
  };
  start_queue: { args: { id: string }; result: DownloadQueue };
  pause_queue: { args: { id: string }; result: DownloadQueue };
  assign_download_to_queue: {
    args: { downloadId: string; queueId: string };
    result: void;
  };
  reorder_queue_items: {
    args: { queueId: string; itemIds: string[] };
    result: void;
  };

  // Credentials
  list_credential_rules: { args: undefined; result: CredentialRule[] };
  save_credential_rule: {
    args: { rule: CredentialRule };
    result: CredentialRule;
  };
  delete_credential_rule: { args: { id: string }; result: void };

  // Proxies
  test_proxy_connection: {
    args: { proxy: ProxySettings; testUrl?: string | null };
    result: ProxyTestResult;
  };
  detect_proxy: { args: undefined; result: DetectedProxyConfig };
  apply_detected_proxy: {
    args: { detected: DetectedProxyConfig };
    result: Settings;
  };

  // Torrents
  torrent_status: { args: undefined; result: TorrentEngineStatus };
  torrent_list: { args: undefined; result: TorrentListItem[] };
  torrent_add_magnet: {
    args: { magnet: string; options?: TorrentAddOptions | null };
    result: TorrentAddResult;
  };
  torrent_add_file: {
    args: { path: string; options?: TorrentAddOptions | null };
    result: TorrentAddResult;
  };
  torrent_action: {
    args: { id: number; action: TorrentActionKind };
    result: void;
  };
  torrent_files: { args: { id: number }; result: TorrentFileItem[] };
  torrent_set_files: { args: { id: number; included: number[] }; result: void };
  torrent_tracker_status: {
    args: { id: number };
    result: TorrentTrackerStatus[];
  };
  torrent_peers: {
    args: { id: number };
    result: TorrentPeerItem[];
  };
  torrent_pieces: {
    args: { id: number };
    result: TorrentPiecesInfo;
  };
  torrent_settings_get: { args: undefined; result: TorrentSettings };
  torrent_settings_set: {
    args: { settings: TorrentSettings };
    result: TorrentSettings;
  };
  torrent_set_watching: { args: { watching: boolean }; result: void };
  torrent_restart_engine: { args: undefined; result: void };
  torrent_take_review: {
    args: undefined;
    result: TorrentReviewRequest | null;
  };
}

/**
 * `update_queue` uses `Option<Option<QueueSchedule>>` on the Rust side: the
 * outer option means "leave the schedule alone", the inner one means "clear".
 * The map cannot express that distinction, so the feature passes `null` to
 * clear and omits the key to keep the current schedule. This alias documents
 * the intent for readers of the queue feature.
 */
export type QueueSchedulePatch = QueueSchedule | null | undefined;

/** Re-exported so feature code never imports a name the map does not use. */
export type { MissedRunPolicy };
